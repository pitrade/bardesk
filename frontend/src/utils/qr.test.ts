import QRCode from 'qrcode'
import { describe, expect, it } from 'vitest'
import { parseJoinLink } from './links'
import { decodeQr } from './qr'

const ID = '8a843490-6569-49eb-b375-61522d36a94f'

describe('parseJoinLink', () => {
  it('reads invite links (with token) and plain group links', () => {
    expect(parseJoinLink(`https://example.org/tab/join/${ID}?t=GR02wIBDukxk7oB_n62eCw`)).toEqual({
      id: ID,
      token: 'GR02wIBDukxk7oB_n62eCw',
    })
    expect(parseJoinLink(`  https://example.org/tab/join/${ID}  `)).toEqual({ id: ID })
  })

  it('rejects anything else', () => {
    expect(parseJoinLink('https://example.com/hello')).toBeNull()
    expect(parseJoinLink('join/not-a-uuid')).toBeNull()
  })
})

describe('decodeQr', () => {
  /** Render a QR code the way a camera sees it: black modules on white, with a quiet zone. */
  function render(text: string, scale = 4, margin = 4) {
    const { modules } = QRCode.create(text, { errorCorrectionLevel: 'M' })
    const size = (modules.size + margin * 2) * scale
    const data = new Uint8ClampedArray(size * size * 4).fill(255)
    for (let y = 0; y < modules.size; y++) {
      for (let x = 0; x < modules.size; x++) {
        if (!modules.get(y, x)) continue
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const i = (((y + margin) * scale + dy) * size + (x + margin) * scale + dx) * 4
            data[i] = data[i + 1] = data[i + 2] = 0
          }
        }
      }
    }
    return { data, width: size, height: size }
  }

  it('decodes an invite QR code as generated by the app', () => {
    const link = `https://example.org/tab/join/${ID}?t=GR02wIBDukxk7oB_n62eCw`
    expect(decodeQr(render(link))).toBe(link)
  })

  it('returns null for an image without a QR code', () => {
    expect(decodeQr({ data: new Uint8ClampedArray(64 * 64 * 4).fill(255), width: 64, height: 64 })).toBeNull()
  })
})
